import type { PrintModuleInput } from './types'

/** What a planned row is wrapped in (`inlineObject`): its members read back as they are written */
const PGRST_OBJECT = `type PgrstObject<R> = [R] extends [unknown] ? { [K in keyof R as K extends string ? \`\${K}\` : K]: R[K] } : never`

const JSON_HELPERS = `export type Json = string | number | boolean | null | { [k: string]: Json | undefined } | Json[]

// what \`const\` inference makes of a literal argument: readonly arrays and objects
export type JsonIn =
  | string
  | number
  | boolean
  | null
  | { readonly [k: string]: JsonIn | undefined }
  | readonly JsonIn[]
`

/** First number of a release line (16.4 is 16), or undefined when it does not start with one. */
function majorOf(version: string | undefined): number | undefined {
  const m = /^\s*v?(\d+)/.exec(version ?? '')
  return m ? Number(m[1]) : undefined
}

/**
 * The version-dependent builder features of a PostgREST release line (`SupabasePgrstStatus['features']`).
 * `max-affected` and spreading to-many embeds arrived in PostgREST 13.
 */
export function pgrstFeatures(postgrestVersion: string | undefined): {
  maxAffected: boolean
  spreadToMany: boolean
} {
  const major = majorOf(postgrestVersion)
  const on = major === undefined || major >= 13
  return { maxAffected: on, spreadToMany: on }
}

/**
 * The generated declaration file: the `SupabaseDatabase` global, the `Json` helpers and the planner status.
 *
 * `selects` and `operands` are where the selects slice plugs in: complete `interface SupabaseSelects { ... }` /
 * `interface SupabaseOperands { ... }` text, spliced verbatim into the `declare global` block.
 */
export function printModule(input: PrintModuleInput): string {
  const features = pgrstFeatures(input.postgrestVersion)
  const parts = [
    `// Generated by @supabase/postgrest-mapper. Do not edit.`,
    `import type { SupabaseColumnType } from '${input.importFrom ?? '@supabase/postgrest-js'}'`,
    ``,
    PGRST_OBJECT,
    ``,
    JSON_HELPERS,
    `declare global {`,
    `  interface SupabaseDatabase {`,
    input.database,
    `  }`,
  ]
  if (input.selects) parts.push('', input.selects.replace(/\n+$/, ''))
  if (input.operands) parts.push('', input.operands.replace(/\n+$/, ''))
  parts.push(
    '',
    `  interface SupabasePgrstStatus {`,
    `    state: 'ready'`,
    `    unplanned: '${input.unplanned ?? 'loose'}'`,
    `    features: { maxAffected: ${features.maxAffected}; spreadToMany: ${features.spreadToMany} }`,
    `  }`,
    `}`,
    ``,
    `export {}`,
    ``
  )
  return parts.join('\n')
}
